export type UiStrings = typeof enUiStrings;
export type UiStringKey = keyof UiStrings;

const zhCnUiStrings: Partial<UiStrings> = {
  // Placeholder only. Add real Simplified Chinese strings later.
};

const dictionaries: Record<UiLocale, Partial<UiStrings>> = {
  en: enUiStrings,
  "zh-CN": zhCnUiStrings,
};

export function getUiStrings(locale: UiLocale = DEFAULT_UI_LOCALE): UiStrings {
  return {
    ...enUiStrings,
    ...(dictionaries[locale] ?? {}),
  };
}

export function serializeUiStringsForInlineScript(locale: UiLocale = DEFAULT_UI_LOCALE): string {
  return JSON.stringify(getUiStrings(locale)).replace(/</g, "\\u003c");
}

export function serializeSelectedUiStringsForInlineScript(
  keys: UiStringKey[],
  locale: UiLocale = DEFAULT_UI_LOCALE,
): string {
  const strings = getUiStrings(locale);
  const selected = Object.fromEntries(keys.map((key) => [key, strings[key]])) as Partial<UiStrings>;
  return JSON.stringify(selected).replace(/</g, "\\u003c");
}
